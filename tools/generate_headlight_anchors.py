"""Generate the per-model Xbox headlight-cone anchors from owned MC3 Remix assets.

Usage: python tools/generate_headlight_anchors.py assets/assets_x.dat_2
The output contains only model names and three local-space coordinates, no game assets.
"""

from __future__ import annotations

import argparse
import struct
import zlib
from pathlib import Path


CHARS = "\x00 #$()-./?0123456789_abcdefghijklmnopqrstuvwxyz~\x7f"
ANCHOR_NAMES = {"headlight_cone", "hl_cone", "hlight_cone"}


def u16(data: bytes, off: int) -> int:
    return struct.unpack_from("<H", data, off)[0]


def u32(data: bytes, off: int) -> int:
    return struct.unpack_from("<I", data, off)[0]


def cstr(data: bytes, off: int) -> str:
    end = data.index(0, off)
    return data[off:end].decode("ascii")


def entries(file):
    magic = file.read(4)
    if magic not in (b"DAVE", b"Dave"):
        raise ValueError("not a DAVE archive")
    count, info_size, _name_size = struct.unpack("<III", file.read(12))
    previous = ""
    for i in range(count):
        file.seek(0x800 + i * 16)
        name_offset, offset, size, compressed_size = struct.unpack("<IIII", file.read(16))
        file.seek(0x800 + info_size + name_offset)
        if magic == b"DAVE":
            name = bytearray()
            while (c := file.read(1)) != b"\0":
                name += c
            name = name.decode("ascii")
        else:
            def bits():
                value = int.from_bytes(file.read(3), "little")
                return [(value >> (j * 6)) & 63 for j in range(4)]

            pending = bits()
            name = ""
            if pending[0] >= 0x38:
                name = previous[: (pending.pop(1) - 0x20) * 8 + pending.pop(0) - 0x38]
            while pending[0]:
                name += CHARS[pending.pop(0)]
                if not pending:
                    pending = bits()
        previous = name
        yield name, offset, size, compressed_size


def anchor(data: bytes) -> tuple[float, float, float]:
    # Xbox vp_*.xbck uses the same 0x44-byte skeleton nodes as PS2. The
    # header pointer at file +0x1AC leads to count and node-list pointer.
    base = u32(data, 0) - 0x80
    table = u32(data, 0x1AC) - base
    if not 0 <= table <= len(data) - 12:
        raise ValueError("bad skeleton table pointer")
    count = u16(data, table)
    nodes = u32(data, table + 8) - base
    if not 1 <= count <= 4096 or not 0 <= nodes <= len(data) - count * 0x44:
        raise ValueError("bad skeleton node list")
    matches = []
    for i in range(count):
        off = nodes + i * 0x44
        name_off = u32(data, off + 0x0C) - base
        if not 0 <= name_off < len(data):
            continue
        try:
            name = cstr(data, name_off).lower()
        except (ValueError, UnicodeError):
            continue
        if name in ANCHOR_NAMES:
            matches.append(struct.unpack_from("<fff", data, off))
    if len(matches) != 1:
        raise ValueError(f"expected one headlight cone, found {len(matches)}")
    x, y, z = matches[0]
    if not -5 < x < 5 or not 0 < y < 4 or not -10 < z < 0:
        raise ValueError(f"implausible anchor {matches[0]}")
    return matches[0]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("--out", type=Path, default=Path("src/game/headlight_anchors.h"))
    args = parser.parse_args()

    models = []
    with args.archive.open("rb") as file:
        for name, offset, size, compressed_size in entries(file):
            parts = name.split("/")
            if (len(parts) != 4 or parts[:2] != ["resources", "vehicle"] or
                    not parts[2].startswith("vp_") or parts[3] != parts[2] + ".xbck"):
                continue
            file.seek(offset)
            payload = file.read(compressed_size)
            if compressed_size != size:
                payload = zlib.decompress(payload, -15)
            if len(payload) != size:
                raise ValueError(f"bad archive entry {name}")
            models.append((parts[2], anchor(payload)))

    models.sort()
    if len({name for name, _ in models}) != len(models):
        raise ValueError("duplicate model names")
    if len(models) < 90:
        raise ValueError(f"only {len(models)} models found")
    def cpp_float(value: float) -> str:
        result = f"{value:.9g}"
        if "." not in result and "e" not in result:
            result += ".0"
        return result + "f"

    lines = [
        "// Generated by tools/generate_headlight_anchors.py from MC3 Remix Xbox assets_x.dat_2.",
        "// The anchor is the model skeleton's headlight_cone / hl_cone / hlight_cone local translation.",
        "#pragma once", "#include <array>", "#include <cstddef>", "#include <string_view>", "", "namespace mc3::headlights {",
        "struct Anchor { std::string_view model; float x, y, z; };",
        f"inline constexpr std::array<Anchor, {len(models)}> kAnchors = {{{{",
    ]
    for name, (x, y, z) in models:
        lines.append(f'    {{"{name}", {cpp_float(x)}, {cpp_float(y)}, {cpp_float(z)}}},')
    lines += ["}};", "", "inline const Anchor* Find(std::string_view model) {",
              "    std::size_t lo = 0, hi = kAnchors.size();",
              "    while (lo < hi) {",
              "        const std::size_t mid = lo + (hi - lo) / 2;",
              "        if (kAnchors[mid].model < model) lo = mid + 1;",
              "        else hi = mid;",
              "    }",
              "    return lo < kAnchors.size() && kAnchors[lo].model == model ? &kAnchors[lo] : nullptr;",
              "}", "}  // namespace mc3::headlights", ""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {len(models)} anchors to {args.out}")


if __name__ == "__main__":
    main()
